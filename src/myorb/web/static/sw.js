// Service worker: makes myOrb installable and shows an offline page when the server cannot be
// reached. Pages and data are never cached; only the offline page and static files are.

const CACHE = "myorb-__VERSION__";
const OFFLINE = "/static/offline.html";
const PRECACHE = [OFFLINE, "/static/style.css", "/static/fonts/fonts.css", "/static/icons/favicon.svg"];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(fetch(request).catch(() => caches.match(OFFLINE)));
    return;
  }

  if (new URL(request.url).pathname.startsWith("/static/")) {
    // Network first, so updates arrive at once; the cached copy only serves when offline.
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => caches.match(request)),
    );
  }
});
